import assert from "node:assert/strict";
import test from "node:test";
import { HarnessFault } from "@earendil-works/pi-agent-core";
import { BACKGROUND_CONTEXT } from "@earendil-works/pi-agent-core/harness/context";
import { fauxAssistantMessage, fauxToolCall } from "@earendil-works/pi-ai";
import { createPilgrimageHarness } from "@animichi/agent/harness";
import { failCommitsAfterEffect } from "../test/native-crash-fixture.ts";
import { catalogHarness } from "./catalog-harness.ts";
import { catalogPostgres } from "./catalog-postgres.ts";
import { seedCatalog } from "./catalog-seed.ts";
import { catalogWorker } from "./catalog-worker.ts";

void test("native translation interrupted after real catalog execution is explicit and never re-executed", { timeout: 360_000 }, async (context) => {
  const database = await catalogPostgres(context); await seedCatalog(database.sql);
  await database.sql`UPDATE bangumi SET title_cn='本地巡礼' WHERE id='1556'`;
  const address = await catalogWorker(context, database.connectionString, database.endpoint);
  const { repo, session, models, toolContext, harness, lane, provider, requests } = await catalogHarness(context, address);
  const reservations: string[] = [];
  toolContext.reserveToolUsage = (id) => { reservations.push(id); return Promise.resolve(); };
  provider.setResponses([fauxAssistantMessage(fauxToolCall("translate_anime_title", { title: "Native Catalog Proof", target_language: "zh" }), { stopReason: "toolUse" })]);
  const fault = failCommitsAfterEffect(session, () => requests.length > 0);
  context.after(() => { fault.mock.restore(); });
  await assert.rejects(lane.prompt("Translate the catalog title", undefined, BACKGROUND_CONTEXT), HarnessFault);
  fault.mock.restore(); await harness.close(BACKGROUND_CONTEXT);
  toolContext.session = await repo.open(session.metadata, BACKGROUND_CONTEXT);
  provider.setResponses([fauxAssistantMessage("Translation outcome is unknown; it was not retried.")]);
  const restored = await createPilgrimageHarness({ session: toolContext.session, models, model: provider.getModel(), toolContext }, BACKGROUND_CONTEXT);
  context.after(() => restored.harness.close(BACKGROUND_CONTEXT));
  const open = restored.open[0]; assert.ok(open);
  const resumed = await restored.harness.lane("main", BACKGROUND_CONTEXT);
  await resumed.drive({ operationId: open.operationId, waitForRetry: false }, BACKGROUND_CONTEXT);
  const entries = await resumed.findEntries({ type: "message" }, BACKGROUND_CONTEXT);
  const results = entries.filter((entry) => entry.type === "message" && entry.message.role === "toolResult");
  assert.equal(results.length, 1);
  const result = results[0]; assert.ok(result?.type === "message" && result.message.role === "toolResult");
  assert.equal(result.message.toolName, "translate_anime_title"); assert.equal(result.message.isError, true);
  assert.match(JSON.stringify(result.message.content), /Tool execution was interrupted/);
  assert.match(JSON.stringify(result.message.content), /external outcome is unknown/);
  assert.deepEqual(requests, ["/catalog/resolve"]); assert.equal(reservations.length, 1);
});
